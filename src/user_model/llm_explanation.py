"""Optional post-ML explanation layer with deterministic offline fallback."""

from __future__ import annotations

import json
import os
import urllib.error
import urllib.request
from typing import Any


def deterministic_explanation(payload: dict[str, Any]) -> str:
    gaps = sorted(payload.get("skill_gaps", []), key=lambda item: item.get("gap", 0), reverse=True)
    strongest = min(gaps, key=lambda item: item.get("gap", 0), default=None)
    largest = gaps[0] if gaps else None
    lines = [
        f"The official difficulty is {payload.get('official_rating')}, while Model 1 independently "
        f"estimates {payload.get('predicted_rating')} from the statement and its own text pipeline.",
        f"For this user, Model 2 estimates a {payload.get('acceptance_probability', 0):.0%} solve chance "
        f"and a personalized difficulty near {payload.get('personalized_rating')}.",
    ]
    if largest:
        lines.append(
            f"The largest measured gap is {largest['topic']}: relevance {largest['required_relevance']:.0%} "
            f"versus skill {largest['user_skill']:.0%}. Study this first, starting below the target rating."
        )
    if strongest:
        lines.append(
            f"The strongest match among the required skills is {strongest['topic']} "
            f"(gap {strongest['gap']:.0%})."
        )
    lines.append(
        "Recommendations are selected from unsolved problems by measured gaps, official ratings, "
        "topic overlap, and a controlled difficulty step. Numerical values are not generated by an LLM."
    )
    return "\n".join(lines)


def _extract_output_text(response: dict[str, Any]) -> str:
    if response.get("output_text"):
        return str(response["output_text"])
    parts = []
    for item in response.get("output", []):
        for content in item.get("content", []):
            if content.get("type") == "output_text" and content.get("text"):
                parts.append(content["text"])
    return "\n".join(parts).strip()


def generate_explanation(payload: dict[str, Any], timeout: float = 20.0) -> dict[str, str]:
    api_key = os.getenv("OPENAI_API_KEY", "").strip()
    model = os.getenv("OPENAI_MODEL", "").strip()
    if not api_key or not model:
        return {"source": "deterministic_fallback", "text": deterministic_explanation(payload)}
    request_payload = {
        "model": model,
        "store": False,
        "max_output_tokens": 450,
        "instructions": (
            "You explain Codeforces learning analytics. Use only the supplied JSON. "
            "Never change, recompute, or invent numerical values. Explain why the problem is difficult, "
            "the user-specific gaps, what to study first, and why the recommendations fit. "
            "Clarify that required-topic percentages are relevance estimates."
        ),
        "input": json.dumps(payload, ensure_ascii=False, sort_keys=True),
    }
    request = urllib.request.Request(
        "https://api.openai.com/v1/responses",
        data=json.dumps(request_payload).encode("utf-8"),
        headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            text = _extract_output_text(json.loads(response.read().decode("utf-8")))
        if not text:
            raise ValueError("The LLM response did not contain output text.")
        return {"source": "openai_responses_api", "text": text}
    except (OSError, ValueError, urllib.error.URLError) as exc:
        fallback = deterministic_explanation(payload)
        return {
            "source": "deterministic_fallback",
            "text": fallback,
            "warning": f"Optional LLM explanation unavailable: {exc}",
        }
